# collect_env.ps1 - record the test environment as a Markdown file.
#
#   .\scripts\collect_env.ps1 -ArmouryMode Performance
#   .\scripts\collect_env.ps1 -OutFile results\run_X_env.md -ArmouryMode Turbo
#
# Everything here is read from the machine at the moment the script runs,
# except the Armoury Crate mode, which Windows does not expose - pass it with
# -ArmouryMode (it is written as "NOT RECORDED" otherwise).
param(
    [string]$OutFile = '',
    [string]$ArmouryMode = ''
)

. "$PSScriptRoot\common.ps1"
if (-not $OutFile) { $OutFile = Join-Path $RepoRoot 'docs\ENVIRONMENT.md' }
Enter-DevShell

# Run a native command and return its output as plain text (stderr included)
# without PowerShell turning stderr lines into errors.
function Invoke-Text([string]$cmdline) { (cmd /c "$cmdline 2>&1") -join "`n" }

$cpu  = Get-CimInstance Win32_Processor | Select-Object -First 1
$cs   = Get-CimInstance Win32_ComputerSystem
$os   = Get-CimInstance Win32_OperatingSystem
$dimm = @(Get-CimInstance Win32_PhysicalMemory)
$caches = Get-CimInstance Win32_CacheMemory | Group-Object Purpose |
    ForEach-Object { '{0}: {1} KB' -f $_.Name, ($_.Group | Measure-Object InstalledSize -Sum).Sum }

# Plugged in or on battery? (Laptops throttle on battery, which ruins benchmarks.)
Add-Type -AssemblyName System.Windows.Forms
$power = [System.Windows.Forms.SystemInformation]::PowerStatus
$powerText = '{0} (battery {1:P0})' -f $power.PowerLineStatus, $power.BatteryLifePercent

$uptime = (Get-Date) - $os.LastBootUpTime
$powerPlan = (powercfg /getactivescheme) -join ' '

$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
$vsName  = & $vswhere -latest -products * -property displayName
$vsVer   = & $vswhere -latest -products * -property catalog_productDisplayVersion
$clBanner = (Invoke-Text 'cl') -split "`n" | Select-Object -First 1
$cmakeVer = (cmake --version | Select-Object -First 1)
$pyVer    = Invoke-Text 'py --version'

$buildType = '(not built)'
$cache = Join-Path $BuildDir 'CMakeCache.txt'
if (Test-Path $cache) {
    $line = Select-String -Path $cache -Pattern '^CMAKE_BUILD_TYPE:STRING=(.*)$' | Select-Object -First 1
    if ($line) { $buildType = $line.Matches[0].Groups[1].Value }
}
$benchInfo  = if (Test-Path $BenchExe)   { Invoke-Text "`"$BenchExe`" --info" } else { '(bench.exe not built)' }
$opensslVer = if (Test-Path $OpenSslExe) { $env:Path = (Join-Path $VcpkgInstalled 'bin') + ';' + $env:Path; Invoke-Text "`"$OpenSslExe`" version -a" } else { '(openssl.exe not found)' }
$baseline = (Get-Content (Join-Path $RepoRoot 'vcpkg-configuration.json') -Raw | ConvertFrom-Json).'default-registry'.baseline
Push-Location $RepoRoot
# "Uncommitted changes" ignores the file this script is about to write.
$outFull = [IO.Path]::GetFullPath($OutFile)
if ($outFull.StartsWith($RepoRoot, [StringComparison]::OrdinalIgnoreCase)) {
    $outRel = $outFull.Substring($RepoRoot.Length).TrimStart('\') -replace '\\', '/'
    $dirty = git status --porcelain -- . ":(exclude)$outRel"
} else {
    $dirty = git status --porcelain
}
$commit = (git rev-parse --short HEAD) + $(if ($dirty) { ' (+ uncommitted changes)' } else { '' })
Pop-Location

$md = @"
# Test environment

Generated by ``scripts/collect_env.ps1`` on $((Get-Date).ToString('yyyy-MM-dd HH:mm:ss zzz')).
Every value below was read from the machine by the script.

## Hardware

| Item | Value |
|---|---|
| Computer | $($cs.Manufacturer) $($cs.Model) |
| CPU | $($cpu.Name.Trim()) |
| Physical cores / logical processors | $($cpu.NumberOfCores) / $($cpu.NumberOfLogicalProcessors) |
| Max clock reported by Windows | $($cpu.MaxClockSpeed) MHz |
| CPU caches (Win32_CacheMemory) | $($caches -join '; ') |
| RAM | $([math]::Round($cs.TotalPhysicalMemory / 1GB, 1)) GB usable, $($dimm.Count) module(s), configured speed $(($dimm | Select-Object -First 1).ConfiguredClockSpeed) MT/s |

## Operating system and power

| Item | Value |
|---|---|
| Windows | $($os.Caption) $($os.OSArchitecture), version $($os.Version) (build $($os.BuildNumber)) |
| Power plan | $powerPlan |
| Power source | $powerText |
| Armoury Crate mode | $(if ($ArmouryMode) { $ArmouryMode } else { 'NOT RECORDED (pass -ArmouryMode)' }) |
| Time since last restart | $([math]::Floor($uptime.TotalHours)) h $($uptime.Minutes) min |

## Software

| Item | Value |
|---|---|
| Visual Studio | $vsName $vsVer |
| C++ compiler | $clBanner |
| CMake | $cmakeVer |
| vcpkg registry baseline | $baseline |
| Build type | $buildType (x64) |
| Build directory | $BuildDir |
| Python | $pyVer |
| Git commit | $commit |

## Benchmark program self-report (``bench --info``)

``````
$benchInfo
``````

## openssl.exe from the same vcpkg build (``openssl version -a``)

``````
$opensslVer
``````
"@

$dir = Split-Path -Parent $OutFile
if ($dir) { New-Item -ItemType Directory -Force $dir | Out-Null }
Set-Content -Path $OutFile -Value $md -Encoding utf8
Write-Host "Wrote $OutFile"
