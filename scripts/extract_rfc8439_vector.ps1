# extract_rfc8439_vector.ps1 - pull the ChaCha20-Poly1305 test vector out of
# the official RFC text (testvectors/rfc8439.txt, downloaded from
# https://www.rfc-editor.org/rfc/rfc8439.txt) and write it in a simple
# "Name = hex" format that kat.cpp reads.
#
# We do this mechanically instead of copying hex by hand so there is no chance
# of a typo, and anyone can re-run it to check our vector file.
. "$PSScriptRoot\common.ps1"

$rfc   = Join-Path $RepoRoot 'testvectors\rfc8439.txt'
$out   = Join-Path $RepoRoot 'testvectors\rfc8439_sec2.8.2.txt'
$lines = Get-Content $rfc

# Section 2.8.2 runs from its heading to the heading of section 3.
$start = ($lines | Select-String -Pattern '^2\.8\.2\.  Example and Test Vector').LineNumber
$end   = ($lines | Select-String -Pattern '^3\.  Implementation Advice').LineNumber
if (-not $start -or -not $end) { throw "Could not find section 2.8.2 in $rfc" }
$section = $lines[$start..($end - 2)]

# Labels in the RFC that we want -> our field names. Every other label
# (keystream, Poly1305 key, ...) is ignored.
$wanted = @{
    'Plaintext:' = 'PT'; 'AAD:' = 'AAD'; 'Key:' = 'Key'; 'IV:' = 'IV'
    '32-bit fixed-common part:' = 'Fixed'; 'Ciphertext:' = 'CT'; 'Tag:' = 'Tag'
}
$bytes = @{}; foreach ($v in $wanted.Values) { $bytes[$v] = New-Object System.Collections.Generic.List[string] }
$current = $null

foreach ($line in $section) {
    $t = $line.Trim()
    if ($t.EndsWith(':') -and $t -notmatch '^[0-9a-f]{2}(:[0-9a-f]{2})+:$') {
        $current = $wanted[$t]          # $null for labels we don't care about
        continue
    }
    if (-not $current) { continue }
    # Hex-dump row: "  016  65 6d 65 ...  ascii". The offset must match the
    # number of bytes collected so far - a built-in sanity check.
    if ($line -match '^\s*(\d{3})  ((?:[0-9a-f]{2} ){0,15}[0-9a-f]{2})(?:\s|$)') {
        $offset = [int]$Matches[1]
        if ($offset -ne $bytes[$current].Count) { throw "$current offset $offset != $($bytes[$current].Count)" }
        $bytes[$current].AddRange([string[]]($Matches[2] -split ' '))
    }
    # Tag row uses "1a:e1:0b:..." format instead.
    elseif ($t -match '^([0-9a-f]{2}(?::[0-9a-f]{2})+)$') {
        $bytes[$current].AddRange([string[]]($Matches[1] -split ':'))
    }
}

# Check lengths against what the RFC says the AEAD uses.
$expect = @{ Key = 32; IV = 8; Fixed = 4; Tag = 16; AAD = 12; PT = 114; CT = 114 }
foreach ($k in $expect.Keys) {
    if ($bytes[$k].Count -ne $expect[$k]) { throw "$k has $($bytes[$k].Count) bytes, expected $($expect[$k])" }
}

# RFC 8439 2.8: nonce = 32-bit constant (fixed-common part) || 64-bit IV.
$nonce = (@($bytes['Fixed']) + @($bytes['IV'])) -join ''
@(
    "# ChaCha20-Poly1305 AEAD test vector, RFC 8439 section 2.8.2"
    "# Source: https://www.rfc-editor.org/rfc/rfc8439.txt"
    "# Generated by scripts/extract_rfc8439_vector.ps1 - do not edit by hand."
    "Key = "   + ($bytes['Key'] -join '')
    "Nonce = " + $nonce
    "AAD = "   + ($bytes['AAD'] -join '')
    "PT = "    + ($bytes['PT'] -join '')
    "CT = "    + ($bytes['CT'] -join '')
    "Tag = "   + ($bytes['Tag'] -join '')
) | Set-Content -Path $out -Encoding ascii
Write-Host "Wrote $out"
Get-Content $out
